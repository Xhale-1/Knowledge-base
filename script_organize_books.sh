#!/bin/bash

# Останавливать скрипт при любой ошибке для безопасности
set -e

# 1. Определяем абсолютный путь к директории, где находится скрипт.
# В вашем случае, это будет /путь/к/stuff/5 knowledge base/
SCRIPT_DIR=$( cd -- "$( dirname -- "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )
echo "Скрипт запущен из директории: $SCRIPT_DIR"

# 2. Определяем исходную и целевую директории
# Исходная папка находится там же, где и скрипт
SOURCE_ROOT="${SCRIPT_DIR}/Knowledge Base"

# -----------------------------------------------------------------------------
# ИЗМЕНЕНИЕ ЗДЕСЬ:
# Целевая директория будет создана в родительской папке для директории скрипта
# (${SCRIPT_DIR}/..  ->  /путь/к/stuff/)
# и будет иметь структуру "5-1 knowledge base books/knowledge base books"
DEST_ROOT="${SCRIPT_DIR}/../5-1 knowledge base books/knowledge base books"
# -----------------------------------------------------------------------------

# 3. Проверяем, существует ли исходная директория "Knowledge Base"
if [ ! -d "$SOURCE_ROOT" ]; then
    echo "Ошибка: Исходная директория не найдена по пути: '$SOURCE_ROOT'"
    exit 1
fi

# 4. Создаем целевую директорию, если она не существует.
# Ключ -p создает всю необходимую структуру (и "5-1...", и вложенную "knowledge base books")
# и не выдает ошибку, если папка уже есть.
echo "Целевая директория: '$DEST_ROOT'"
mkdir -p "$DEST_ROOT"

# 5. Ищем файлы и перемещаем их
echo "Начинаю поиск файлов в папках 'литра'..."

# Находим все файлы (-type f), путь к которым содержит /литра/
# и передаем их в цикл для обработки.
find "$SOURCE_ROOT" -type f \( -path "*/литра/*" -o -path "*[0-9]*литра*" -o -path "*Литра*" -o -path "*[0-9]* литра*" -o -path "*[0-9]*  литра*" \) -print0 | while IFS= read -r -d '' source_file; do    
    # 6. Для каждого файла вычисляем его путь относительно "Knowledge Base"
    # Пример: из "/.../Knowledge Base/IT/литра/book.pdf"
    # получаем "IT/литра/book.pdf"
    relative_path="${source_file#"$SOURCE_ROOT/"}"

    # 7. Формируем полный путь к файлу в целевой директории
    # Пример: "/.../stuff/5-1 knowledge base books/knowledge base books" + "/" + "IT/литра/book.pdf"
    dest_file="${DEST_ROOT}/${relative_path}"

    # 8. Создаем директорию для целевого файла (если ее еще нет)
    dest_dir_for_file=$(dirname "$dest_file")
    mkdir -p "$dest_dir_for_file"

    # 9. Перемещаем файл, ключ -v (verbose) выводит информацию о перемещении
    echo "Перемещение: '$relative_path'"
    mv -v "$source_file" "$dest_file"
done

echo "========================================="
echo "Перемещение файлов успешно завершено!"